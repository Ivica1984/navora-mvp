#!/usr/bin/env node
// STAB-1 (founder 2026-11-20, issue #1587; proposal docs/engineering/probes/STAB-1_PROPOSAL.md).
// One readable source file per BK database function, generated from the database, checked for drift in CI.
//
//   node scripts/fn-source.mjs dump  [--out <dir>]   write supabase/schema/functions/<schema>.<name>.sql from the DB
//   node scripts/fn-source.mjs check                 red when a file and the DB differ by one character, when a
//                                                    required property (MANIFEST.json) is missing, or a file is stale
//   node scripts/fn-source.mjs migration <names...>  print a migration body that re-creates whole files (no patch)
//
// The database is read only (`select` on pg_proc). FN_DB_URL defaults to the local Supabase stack used in CI.
// Deterministic, no AI, fail-closed: any query or parse error is an error, never a pass.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const DIR = "supabase/schema/functions";
const DB = process.env.FN_DB_URL ?? "postgresql://postgres:postgres@127.0.0.1:54322/postgres";

export function loadManifest(dir = DIR) {
  const m = JSON.parse(readFileSync(join(dir, "MANIFEST.json"), "utf8"));
  if (!Array.isArray(m.functions) || m.functions.length === 0) throw new Error("MANIFEST.json lists no functions");
  return m.functions;
}

/** «public.take_order(uuid, …)» → «public.take_order» */
export function qualifiedName(signature) {
  const m = /^([a-z_]+\.[a-z0-9_]+)\(/.exec(signature);
  if (!m) throw new Error(`not a qualified signature: ${signature}`);
  return m[1];
}

function sqlLiteral(s) {
  return `'${s.replaceAll("'", "''")}'`;
}

/** Reads definition, execute grantees and comment of every manifest signature in one read-only query. */
export function readFromDb(functions) {
  const names = functions.map((f) => sqlLiteral(f.name)).join(", ");
  const sql = `
    select coalesce(json_agg(json_build_object(
      'name', s.name,
      'signature', s.name || '(' || pg_get_function_identity_arguments(p.oid) || ')',
      'definition', pg_get_functiondef(p.oid),
      'acl_set', p.proacl is not null,
      'grantees', (select coalesce(json_agg(distinct case when a.grantee = 0 then 'public' else r.rolname end
                                            order by case when a.grantee = 0 then 'public' else r.rolname end), '[]')
                   from aclexplode(p.proacl) a left join pg_roles r on r.oid = a.grantee
                   where a.privilege_type = 'EXECUTE' and a.grantee <> p.proowner),
      'comment', obj_description(p.oid, 'pg_proc')
    ) order by s.ord, pg_get_function_identity_arguments(p.oid)), '[]')
    from unnest(array[${names}]) with ordinality as s(name, ord)
    join pg_namespace n on n.nspname = split_part(s.name, '.', 1)
    join pg_proc p on p.pronamespace = n.oid and p.proname = split_part(s.name, '.', 2)`;
  const out = execFileSync("psql", [DB, "-AtX", "-v", "ON_ERROR_STOP=1", "-c", sql], { encoding: "utf8" });
  const rows = JSON.parse(out);
  const missing = functions.filter((f) => !rows.some((r) => r.name === f.name)).map((f) => f.name);
  if (missing.length) throw new Error(`not in the database: ${missing.join(", ")}`);
  return rows;
}

/** The canonical file text of one function name (all its listed overloads, manifest order). */
export function renderFile(name, rows) {
  const parts = [
    `-- ${name}: canonical source (STAB-1). Generated by scripts/fn-source.mjs from the database; edit THIS file and`,
    `-- ship the whole file in a new migration (node scripts/fn-source.mjs migration ${name}). No text patch.`,
    "",
  ];
  for (const r of rows) {
    parts.push(`-- ${r.signature}`, `${r.definition.trimEnd()};`, "");
    if (r.acl_set) {
      parts.push(`revoke all on function ${r.signature} from public, anon, authenticated, service_role;`);
      for (const g of r.grantees) parts.push(`grant execute on function ${r.signature} to ${g};`);
    }
    if (r.comment !== null && r.comment !== undefined) parts.push(`comment on function ${r.signature} is ${sqlLiteral(r.comment)};`);
    parts.push("");
  }
  return parts.join("\n");
}

export function renderAll(functions, rows) {
  const byName = new Map();
  rows.forEach((r) => {
    const n = r.name;
    if (!byName.has(n)) byName.set(n, []);
    byName.get(n).push(r);
  });
  return new Map([...byName].map(([n, rs]) => [`${n}.sql`, renderFile(n, rs)]));
}

/** Required substrings (MANIFEST «required») that a definition lost. */
export function missingRequired(functions, rows) {
  const problems = [];
  for (const f of functions) {
    for (const r of rows.filter((x) => x.name === f.name)) {
      for (const req of f.required ?? []) {
        if (!r.definition.includes(req)) problems.push(`${r.signature}: lost required «${req}»`);
      }
    }
  }
  return problems;
}

function main(argv) {
  const [cmd, ...rest] = argv;
  const functions = loadManifest();
  if (cmd === "dump" || cmd === "check") {
    const rows = readFromDb(functions);
    const files = renderAll(functions, rows);
    const problems = missingRequired(functions, rows);
    if (cmd === "dump") {
      const out = rest[0] === "--out" ? rest[1] : DIR;
      mkdirSync(out, { recursive: true });
      for (const [f, text] of files) writeFileSync(join(out, f), text);
      console.log(`fn-source: wrote ${files.size} files for ${rows.length} definitions to ${out}`);
      problems.forEach((p) => console.error(`fn-source: ${p}`));
      process.exit(problems.length ? 1 : 0);
    }
    for (const [f, text] of files) {
      const path = join(DIR, f);
      if (!existsSync(path)) problems.push(`${path}: missing (run: node scripts/fn-source.mjs dump)`);
      else if (readFileSync(path, "utf8") !== text) problems.push(`${path}: differs from the database (drift)`);
    }
    for (const f of readdirSync(DIR)) {
      if (f.endsWith(".sql") && !files.has(f)) problems.push(`${join(DIR, f)}: not in MANIFEST.json`);
    }
    problems.forEach((p) => console.error(`::error title=fn-source drift (STAB-1)::${p}`));
    if (problems.length === 0) console.log(`fn-source: ${rows.length} definitions in ${files.size} files match the database`);
    process.exit(problems.length ? 1 : 0);
  }
  if (cmd === "migration") {
    if (rest.length === 0) throw new Error("name at least one function, e.g. public.take_order");
    const body = rest.map((n) => readFileSync(join(DIR, `${n}.sql`), "utf8")).join("\n");
    process.stdout.write(`-- Whole-file re-creation from ${DIR} (STAB-1); generated by scripts/fn-source.mjs.\n\n${body}`);
    return;
  }
  console.error("usage: fn-source.mjs dump [--out <dir>] | check | migration <schema.name>...");
  process.exit(2);
}

if (import.meta.url === `file://${process.argv[1]}`) main(process.argv.slice(2));
