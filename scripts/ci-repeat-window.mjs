#!/usr/bin/env node
// ADR-198 (PO hypothesis H-BK-00:39, journal 2026-11-17-0039-po): a ci-repeat run marks itself as acceptance evidence
// or not, by the Zurich time it started and ended. The e2e acceptance tests guard themselves at night (ADR-113, the
// BD-2 run-through and the F3/F7 field specs skip before 02:20 / 00:30 Zurich); a skipped test is not a verifying run
// (FE-071 (4)). A repeat run that starts before 02:20 or ends at or after 22:20 Zurich, or crosses midnight, is
// therefore labelled "NOT acceptance evidence" in its summary and with a warning annotation, so a night run cannot be
// mistaken for the 10/10 record. Inside the window is necessary, not sufficient: the reader still reads the skip and
// pass counts in the raw logs. This script never fails a job and never changes a test (it weakens no check).
//
// CLI (in .github/workflows/ci-repeat.yml, generated by scripts/ci-repeat.mjs):
//   node scripts/ci-repeat-window.mjs start     writes started=<ISO now> to $GITHUB_OUTPUT
//   node scripts/ci-repeat-window.mjs verdict   reads REPEAT_STARTED (ISO), ends now; writes the verdict to
//                                               $GITHUB_STEP_SUMMARY and an annotation to stdout
// REPEAT_WINDOW_NOW (ISO) replaces the clock, for tests/unit/ci-repeat-window.test.ts only.
import { appendFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

/** Zurich wall-clock window for acceptance runs: start at or after `from`, end before `until`, same Zurich day. */
export const WINDOW = Object.freeze({ from: "02:20", until: "22:20" });

const FMT = new Intl.DateTimeFormat("en-CA", {
  timeZone: "Europe/Zurich",
  year: "numeric",
  month: "2-digit",
  day: "2-digit",
  hour: "2-digit",
  minute: "2-digit",
  hourCycle: "h23",
});

/** @param {Date} d @returns {{ day: string, hm: string }} Zurich calendar day (YYYY-MM-DD) and time (HH:MM). */
export function zurich(d) {
  if (!(d instanceof Date) || Number.isNaN(d.getTime())) throw new Error("ci-repeat-window: invalid date");
  const p = Object.fromEntries(FMT.formatToParts(d).map((x) => [x.type, x.value]));
  return { day: `${p.year}-${p.month}-${p.day}`, hm: `${p.hour}:${p.minute}` };
}

/**
 * @param {string | undefined} startedIso when the run started (ISO); missing or invalid counts as outside (fail closed)
 * @param {string} endedIso when the run ended (ISO)
 * @returns {{ inside: boolean, reason: string, start: string, end: string }}
 */
export function verdict(startedIso, endedIso) {
  const ended = zurich(new Date(endedIso));
  const endText = `${ended.day} ${ended.hm}`;
  const started = startedIso ? new Date(startedIso) : null;
  if (!started || Number.isNaN(started.getTime())) {
    return { inside: false, reason: "start time unknown", start: "unknown", end: endText };
  }
  const s = zurich(started);
  const startText = `${s.day} ${s.hm}`;
  let reason = "";
  if (s.day !== ended.day) reason = "the run crossed midnight Europe/Zurich";
  else if (s.hm < WINDOW.from) reason = `started before ${WINDOW.from} Zurich`;
  else if (ended.hm >= WINDOW.until) reason = `ended at or after ${WINDOW.until} Zurich`;
  return { inside: reason === "", reason, start: startText, end: endText };
}

/** @param {ReturnType<typeof verdict>} v @returns {{ annotation: string, summary: string }} */
export function report(v) {
  const span = `start ${v.start}, end ${v.end} (Europe/Zurich); window ${WINDOW.from}–${WINDOW.until}, one day`;
  if (v.inside) {
    return {
      annotation: `::notice title=ci-repeat window::Inside the e2e acceptance window: ${span}. Still read the skip and pass counts in the raw logs (FE-071 (4)).`,
      summary:
        `### ci-repeat window: inside\n\n${span}.\n\n` +
        "Inside the window is necessary, not sufficient: acceptance also needs every attempt green with 0 skipped in the raw logs (FE-071 (4)).\n",
    };
  }
  return {
    annotation: `::warning title=ci-repeat window::NOT acceptance evidence: ${v.reason}; ${span}. The night guards of the e2e acceptance specs skip outside the window (ADR-113, ADR-198).`,
    summary:
      `### ci-repeat window: NOT acceptance evidence\n\n${v.reason}; ${span}.\n\n` +
      "The e2e acceptance specs skip themselves outside the window (ADR-113), and a skipped test is not a verifying run (FE-071 (4)). " +
      "Use this run as a probe only; start the acceptance repeat inside the window (ADR-198).\n",
  };
}

function main() {
  const mode = process.argv[2];
  const now = process.env.REPEAT_WINDOW_NOW || new Date().toISOString();
  if (mode === "start") {
    const line = `started=${now}\n`;
    if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, line);
    const z = zurich(new Date(now));
    console.log(`ci-repeat window: run started ${z.day} ${z.hm} Europe/Zurich (${now})`);
    return;
  }
  if (mode === "verdict") {
    const r = report(verdict(process.env.REPEAT_STARTED, now));
    if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, r.summary);
    console.log(r.annotation);
    return;
  }
  console.error("usage: ci-repeat-window.mjs start|verdict");
  process.exit(2);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
