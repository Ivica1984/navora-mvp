-- AI1 (PO package contract 2026-11-22 08:39; review finding R7 on draft #1697, 2026-11-24 08:2x CET, and `aia` AUT-197,
-- review 86): a ledger proposal of the report-draft model needs a provider call behind it.
-- Before (IMPLEMENTED, 0151): `public.record_report_draft_proposal(report, model, lines, key)` checked only the closed-check
--   and its own key. A signed-in performer could write model-labelled lines over PostgREST with no reserved call, any
--   number of times; `aig1_window_stats` counts every ledger row, so such lines moved the stop rule both ways.
-- Now:
--   1. `private.model_call_reservations` gets `agent_version` (stamped by `reserve_report_draft_call` from the version whose
--      prompt digest it checked), `proposal_id` (unique; set once by the record) and `model` (the model id the record
--      named; session-reported, see limit below). Existing rows keep NULL: no reservation was ever admitted on staging
--      (price row NULL, `price_missing`), and a NULL `agent_version` refuses the record (fail closed).
--   2. `public.record_report_draft_proposal(report, reservation, model, lines, key)`: after the unchanged closed-check, the
--      reservation must belong to this report, be settled with outcome `ok` and carry no proposal yet; the ledger rows take
--      `agent_version` from it. Refusals: reservation_missing | reservation_not_ok | reservation_used |
--      reservation_unversioned. LEAVE1 `assert_access_open()` is now called first (before: only via the closed-check).
--   3. The 4-argument form is DROPPED in this migration (otherwise it stays a bypass, as 0167 did for reserve).
-- Lock order: report row, then reservation row (reserve: report row, then advisory lock; settle: reservation row, then
-- advisory lock); no cycle.
-- Residual limit (OPEN, ADR-227 addendum 03:30 (2)): settle still runs under the user session, so a malicious performer can
-- reserve + settle `ok` + record directly, but now at most twice per report version and counted against the day cap.
-- Function sources: supabase/schema/functions/ (STAB-1), whole files, rendered by scripts/fn-source.mjs (no text patch);
-- the previous definitions: reserve = STAB-1 file after 0168, record = 0151 (no later migration names it).
-- Way back: a forward migration that re-creates the 0151 form; the new columns may stay (nullable).
-- Idempotent: add column if not exists, create unique index if not exists, drop constraint if exists + add,
-- drop function if exists, `create or replace`, revoke/grant/comment repeat safely.

