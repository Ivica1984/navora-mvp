-- public.record_report_draft_proposal(p_report_id uuid, p_reservation_id uuid, p_model text, p_lines jsonb, p_idempotency_key uuid)
CREATE OR REPLACE FUNCTION public.record_report_draft_proposal(p_report_id uuid, p_reservation_id uuid, p_model text, p_lines jsonb, p_idempotency_key uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  uid  uuid := (select auth.uid());
  r    public.visit_reports%rowtype;
  m    private.model_call_reservations%rowtype;
  why  text;
  done jsonb;
begin
  if p_model is null or p_model !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,79}$' then
    raise exception 'model id invalid' using errcode = '22023';
  end if;
  if not private.report_draft_lines_ok(p_lines) then
    raise exception 'lines invalid' using errcode = '22023';
  end if;
  if p_reservation_id is null then
    raise exception 'reservation id is required' using errcode = '22023';
  end if;
  perform private.assert_access_open();  -- LEAVE1: an ended access records nothing (also checked in the closed-check)
  if private.begin_command('record_report_draft_proposal', p_idempotency_key) then
    perform private.end_command('duplicate');
    select jsonb_agg(jsonb_build_object('line_index', (s.proposed_value ->> 'line_index')::int, 'suggestion_id', s.id)
                     order by s.seq)
      into done from public.ai_suggestions s
      where s.proposal_id = p_idempotency_key and s.agent_key = 'report_draft_model' and s.entity_id = p_report_id;
    return jsonb_build_object('result', 'duplicate', 'proposal_id', p_idempotency_key, 'lines', coalesce(done, '[]'::jsonb));
  end if;
  -- Lock order as in reserve (report row first), then the reservation row: one proposal per reservation.
  select * into r from public.visit_reports v where v.id = p_report_id for update;
  why := private.report_draft_model_closed(r, uid);
  if why is not null then
    perform private.end_command('rejected');
    return jsonb_build_object('result', 'rejected', 'reason', why);
  end if;
  -- #1697 R7 / AUT-197: a ledger proposal only for a provider call that was reserved for this report and settled with
  -- outcome ok, once. Without it, model-labelled lines with no call behind them would move the stop rule both ways.
  select * into m from private.model_call_reservations x where x.id = p_reservation_id for update;
  if m.id is null or m.report_id is distinct from r.id or m.function_key <> 'report_draft_model' then
    perform private.end_command('rejected');
    return jsonb_build_object('result', 'rejected', 'reason', 'reservation_missing');
  end if;
  if m.settled_at is null or m.outcome is distinct from 'ok' then
    perform private.end_command('rejected');
    return jsonb_build_object('result', 'rejected', 'reason', 'reservation_not_ok');
  end if;
  if m.proposal_id is not null then
    perform private.end_command('rejected');
    return jsonb_build_object('result', 'rejected', 'reason', 'reservation_used');
  end if;
  if m.agent_version is null then
    perform private.end_command('rejected');
    return jsonb_build_object('result', 'rejected', 'reason', 'reservation_unversioned');
  end if;
  -- The agent version is the one the call was reserved under (its prompt digest was checked then), never read again here.
  insert into public.ai_suggestions (proposal_id, organization_id, team_id, case_id, agent_key, agent_version, field,
                                     entity_type, entity_id, input_refs, proposed_value)
  select p_idempotency_key, r.organization_id, r.team_id, r.case_id, 'report_draft_model', m.agent_version, 'summary_line',
         'visit_reports', r.id,
         jsonb_build_array(jsonb_build_object('table', 'visit_reports', 'id', r.id),
                           jsonb_build_object('table', 'care_visits', 'id', r.visit_id)),
         jsonb_build_object('line_index', (l.n - 1)::int,
                            'sources', (select jsonb_agg(distinct x) from jsonb_array_elements_text(l.e -> 'sources') x),
                            'digest', private.report_draft_digest(btrim(l.e ->> 'text')),
                            'length', char_length(btrim(l.e ->> 'text')),
                            'model', p_model)
  from jsonb_array_elements(p_lines) with ordinality l(e, n)
  order by l.n;
  update private.model_call_reservations set proposal_id = p_idempotency_key, model = p_model where id = m.id;
  select jsonb_agg(jsonb_build_object('line_index', (s.proposed_value ->> 'line_index')::int, 'suggestion_id', s.id)
                   order by s.seq)
    into done from public.ai_suggestions s
    where s.proposal_id = p_idempotency_key and s.agent_key = 'report_draft_model' and s.entity_id = r.id;
  perform private.end_command('ok');
  return jsonb_build_object('result', 'ok', 'proposal_id', p_idempotency_key, 'lines', done);
end;
$function$;

