-- public.plan_visit(p_case_id uuid, p_visit_date date, p_time_start time without time zone, p_time_end time without time zone, p_minutes_a integer, p_minutes_b integer, p_minutes_c integer, p_needs_assessment boolean, p_responsible_user_id uuid, p_idempotency_key uuid, p_overlap_shown boolean, p_member_overlap_shown boolean)
CREATE OR REPLACE FUNCTION public.plan_visit(p_case_id uuid, p_visit_date date, p_time_start time without time zone, p_time_end time without time zone, p_minutes_a integer, p_minutes_b integer, p_minutes_c integer, p_needs_assessment boolean, p_responsible_user_id uuid, p_idempotency_key uuid, p_overlap_shown boolean DEFAULT NULL::boolean, p_member_overlap_shown boolean DEFAULT NULL::boolean)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  uid  uuid := (select auth.uid());
  c    public.cases%rowtype;
  a    integer := coalesce(p_minutes_a, 0);
  b    integer := coalesce(p_minutes_b, 0);
  cc   integer := coalesce(p_minutes_c, 0);
  na   boolean := coalesce(p_needs_assessment, false);
  vid  uuid;
  services text[];
  mo   boolean;
  tk   uuid;
begin
  if uid is null then
    return jsonb_build_object('result', 'rejected', 'reason', 'not_team_member');
  end if;
  perform private.check_visit_slot(p_visit_date, p_time_start, p_time_end);
  if a < 0 or b < 0 or cc < 0 or a + b + cc = 0 then
    raise exception 'planned minutes per category are required' using errcode = '22023';
  end if;

  if private.begin_command('plan_visit', p_idempotency_key) then
    perform private.end_command('duplicate');
    return jsonb_build_object('result', 'duplicate');
  end if;

  select * into c from public.cases where id = p_case_id for update;
  if not found or c.assigned_team_id is null
     or not private.is_org_member(c.organization_id)
     or not private.is_team_member(c.assigned_team_id) then
    perform private.end_command('rejected');
    return jsonb_build_object('result', 'rejected', 'reason', 'not_team_member');
  end if;

  if a + b + cc > extract(epoch from (p_time_end - p_time_start)) / 60 then
    perform private.end_command('rejected');
    return jsonb_build_object('result', 'rejected', 'reason', 'minutes_exceed_window');
  end if;

  -- Needs assessment first (KLV Art. 8a)
  if c.needs_assessment_done_at is null then
    if not na then
      perform private.end_command('rejected');
      return jsonb_build_object('result', 'rejected', 'reason', 'assessment_first');
    end if;
    if exists (select 1 from public.care_visits v where v.case_id = c.id and v.is_needs_assessment
               and v.status in ('planned', 'on_the_way', 'started', 'paused')) then
      perform private.end_command('rejected');
      return jsonb_build_object('result', 'rejected', 'reason', 'assessment_already_planned');
    end if;
  end if;
  if na and (b > 0 or cc > 0) then
    perform private.end_command('rejected');
    return jsonb_build_object('result', 'rejected', 'reason', 'assessment_category_a_only');
  end if;

  -- Category B needs a medical order
  if b > 0 and c.medical_order_status is distinct from 'present' then
    perform private.end_command('rejected');
    return jsonb_build_object('result', 'rejected', 'reason', 'order_required');
  end if;

  -- Responsible member
  if p_responsible_user_id is not null then
    if not exists (select 1 from public.team_memberships m
                   where m.team_id = c.assigned_team_id and m.user_id = p_responsible_user_id)
       or private.access_ended(p_responsible_user_id) /* LEAVE1-14 */ then
      perform private.end_command('rejected');
      return jsonb_build_object('result', 'rejected', 'reason', 'responsible_not_in_team');
    end if;
    if (b > 0 or na) and not private.is_registered_nurse(c.assigned_team_id, p_responsible_user_id) then
      perform private.end_command('rejected');
      return jsonb_build_object('result', 'rejected', 'reason', 'rn_required');
    end if;
    -- ADM2-6: never to a member without a qualification (ADR-114).
    if not private.has_qualification(c.assigned_team_id, p_responsible_user_id) then
      perform private.end_command('rejected');
      return jsonb_build_object('result', 'rejected', 'reason', 'qualification_missing');
    end if;
    -- ADM2-11: never for a date outside her recorded contract (ADR-115).
    if not private.adm2_in_contract(c.organization_id, p_responsible_user_id, p_visit_date) then
      perform private.end_command('rejected');
      return jsonb_build_object('result', 'rejected', 'reason', 'outside_contract');
    end if;
    -- ABS1-C4: never to a member absent at the visit's interval (the one interval of 0048; the person, not the team).
    if (select private.member_absent_during(c.assigned_team_id, p_responsible_user_id, lower(x.iv), upper(x.iv))
        from (select private.visit_interval(jsonb_populate_record(null::public.care_visits, jsonb_build_object(
                'visit_date', p_visit_date, 'time_start', p_time_start, 'time_end', p_time_end,
                'planned_minutes_a', a, 'planned_minutes_b', b, 'planned_minutes_c', cc))) as iv) x) then
      perform private.end_command('rejected');
      return jsonb_build_object('result', 'rejected', 'reason', 'responsible_absent');
    end if;
    -- HD-3s-F2-F1 (PO decision CGR-289 (c), ADR-230): never into the window of her live take (pause included); the
    -- rejection names the take, nothing is written and the take stays live. The person lock first (BK-E1B-L), so a take
    -- of hers in flight is waited for and then seen.
    perform pg_advisory_xact_lock(hashtextextended('order_take_member:' || p_responsible_user_id::text, 0));
    tk := private.member_take_window(p_responsible_user_id,
            private.visit_interval(jsonb_populate_record(null::public.care_visits, jsonb_build_object(
              'visit_date', p_visit_date, 'time_start', p_time_start, 'time_end', p_time_end,
              'planned_minutes_a', a, 'planned_minutes_b', b, 'planned_minutes_c', cc))), null);
    if tk is not null then
      perform private.end_command('rejected');
      return jsonb_build_object('result', 'rejected', 'reason', 'member_take_window',
                                'take', private.member_take_window_facts(tk, c.assigned_team_id));
    end if;
  end if;

  select coalesce(array_agg(distinct i.service), c.care_needs, '{}') into services
  from public.care_plan_items i where i.case_id = c.id and i.active;

