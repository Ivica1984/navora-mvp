-- private.guard_take_window()
CREATE OR REPLACE FUNCTION private.guard_take_window()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  slot_new boolean;
  tk       uuid;
  who      uuid;
begin
  -- HD-3s-F2-F1 (CGR-289, ADR-230): the database backstop. No writer may attach a person to a visit inside the window
  -- of her own live take (pause included): before the start that write released the whole take silently
  -- (recheck_member_takes, step 3), after the start it made a false take_member_dropped. The hand commands reject
  -- earlier with the take named; this raises for every other writer (fail closed, never a silent release).
  if new.status not in ('planned', 'on_the_way', 'started', 'paused') then
    return new;
  end if;
  -- A status step or any other change of an unchanged slot never raises: documenting a visit stays possible.
  slot_new := tg_op = 'INSERT'
              or old.status not in ('planned', 'on_the_way', 'started', 'paused')
              or new.visit_date is distinct from old.visit_date
              or new.time_start is distinct from old.time_start
              or new.time_end is distinct from old.time_end
              or new.planned_minutes_a is distinct from old.planned_minutes_a
              or new.planned_minutes_b is distinct from old.planned_minutes_b
              or new.planned_minutes_c is distinct from old.planned_minutes_c;
  -- The person locks of the row in one fixed order (as recheck_takes_trigger, CGR-255), so a take in flight is waited for.
  if new.responsible_user_id is not null and new.covered_by is not null
     and new.covered_by is distinct from new.responsible_user_id then
    perform pg_advisory_xact_lock(hashtextextended('order_take_member:'
              || least(new.responsible_user_id, new.covered_by)::text, 0));
    perform pg_advisory_xact_lock(hashtextextended('order_take_member:'
              || greatest(new.responsible_user_id, new.covered_by)::text, 0));
  elsif coalesce(new.responsible_user_id, new.covered_by) is not null then
    perform pg_advisory_xact_lock(hashtextextended('order_take_member:'
              || coalesce(new.responsible_user_id, new.covered_by)::text, 0));
  end if;
  foreach who in array array[
      case when slot_new or new.responsible_user_id is distinct from old.responsible_user_id
           then new.responsible_user_id end,
      case when slot_new or new.covered_by is distinct from old.covered_by then new.covered_by end] loop
    continue when who is null;
    tk := private.member_take_window(who, private.visit_interval(new), new.order_take_id);
    if tk is not null then
      raise exception 'member_take_window: the visit lies in the window of a live take of its person'
        using errcode = 'P0001', detail = 'take ' || tk::text,
              hint = 'Plan another person or another time; the take is released only through its own release.';
    end if;
  end loop;
  return new;
end;
$function$;

