CREATE OR REPLACE FUNCTION public.institution_set_planning_limits(p_institution_id uuid, p_min_rest_hours integer, p_max_consecutive_days integer, p_weekly_target_hours numeric, p_expected jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  h public.institutions;
begin
  perform private.assert_access_open();  -- LEAVE1-3
  -- Only the lead sets the home's planning limits (a planner plans within them).
  if p_institution_id is null or not private.is_institution_member(p_institution_id, array['lead']) then
    return jsonb_build_object('result', 'rejected');
  end if;
  -- Founder parameters for the simulation (FE-119), «Arbeitszeitgesetz nicht abschliessend geprüft»; the ranges are
  -- input checks only, not a legal rule.
  if p_min_rest_hours is null or p_min_rest_hours < 1 or p_min_rest_hours > 24
     or p_max_consecutive_days is null or p_max_consecutive_days < 1 or p_max_consecutive_days > 14 then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('limits_not_valid'));
  end if;
  -- FE-123: 100 % Pensum = the home's «Sollstunden pro Woche» (test home 42 h, «Beispielwert des Heims»). NULL = not
  -- entered: the draft then refuses to run (fail closed). 1-80 h is an input check only, not a working-time rule.
  if p_weekly_target_hours is not null and (p_weekly_target_hours < 1 or p_weekly_target_hours > 80) then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('weekly_target_hours_not_valid'));
  end if;
  -- HD-3a-F1 R-6-2 (b): the values the form showed. Every key is required: a missing key is not «nicht eingetragen»
  -- (JSON null), so a form that forgot a field writes nothing (fail closed).
  if p_expected is null or jsonb_typeof(p_expected) <> 'object'
     or not (p_expected ?& array['min_rest_hours', 'max_consecutive_days', 'weekly_target_hours'])
     or jsonb_typeof(p_expected -> 'min_rest_hours') <> 'number'
     or jsonb_typeof(p_expected -> 'max_consecutive_days') <> 'number'
     or jsonb_typeof(p_expected -> 'weekly_target_hours') not in ('number', 'null') then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('expected_not_valid'));
  end if;
  select * into h from public.institutions where id = p_institution_id for update;
  if h.id is null then
    return jsonb_build_object('result', 'rejected');
  end if;
  -- Compared under the one row lock (no second read): a value changed by somebody else since the form was shown is
  -- never overwritten silently; nothing is written, the screen reloads the current values. Typed compare (42 = 42.0).
  if (p_expected ->> 'min_rest_hours')::numeric is distinct from h.min_rest_hours
     or (p_expected ->> 'max_consecutive_days')::numeric is distinct from h.max_consecutive_days
     or (p_expected ->> 'weekly_target_hours')::numeric is distinct from h.weekly_target_hours then
    return jsonb_build_object('result', 'conflict', 'problems', jsonb_build_array('changed_meanwhile'));
  end if;
  update public.institutions set min_rest_hours = p_min_rest_hours, max_consecutive_days = p_max_consecutive_days,
    weekly_target_hours = p_weekly_target_hours
    where id = h.id;
  perform private.institution_audit(h.id, 'institution_set_planning_limits', 'institutions', h.id,
    jsonb_build_object('min_rest_hours', jsonb_build_object('old', h.min_rest_hours, 'new', p_min_rest_hours),
                       'max_consecutive_days', jsonb_build_object('old', h.max_consecutive_days, 'new', p_max_consecutive_days),
                       'weekly_target_hours', jsonb_build_object('old', h.weekly_target_hours, 'new', p_weekly_target_hours)));
  return jsonb_build_object('result', 'ok');
end $function$;

