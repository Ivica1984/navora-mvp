-- public.institution_set_staff_wishes(p_staff_id uuid, p_wishes jsonb)
CREATE OR REPLACE FUNCTION public.institution_set_staff_wishes(p_staff_id uuid, p_wishes jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  p public.institution_staff;
  w jsonb;
  old_set jsonb;
  new_set jsonb;
begin
  perform private.assert_access_open();  -- LEAVE1-3
  -- Membership first, then the row lock (a non-member never holds a lock on the home's staff row).
  if p_staff_id is null or not private.is_institution_member(
       (select s.institution_id from public.institution_staff s where s.id = p_staff_id), array['lead', 'planner']) then
    return jsonb_build_object('result', 'rejected');
  end if;
  -- HD-3a wishes (FE-125, brief HD.md §5b): an ISO weekday (1 = Monday ... 7 = Sunday) with a shift type of the home
  -- (`work`, W-1) or without work (`off`, W-2). A wish is only an order among permitted persons and never breaks a
  -- mandatory rule. No free text and no reason (no health data). The call replaces the whole set of the person.
  -- Up to 70 entries is an input check only.
  if p_wishes is null or jsonb_typeof(p_wishes) <> 'array' or jsonb_array_length(p_wishes) > 70 then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('wishes_not_valid'));
  end if;
  for w in select e from jsonb_array_elements(p_wishes) e loop
    -- Nested checks: SQL does not promise the order of OR, and jsonb_object_keys raises on a non-object.
    if jsonb_typeof(w) <> 'object' then
      return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('wishes_not_valid'));
    end if;
    if exists (select 1 from jsonb_object_keys(w) k where k not in ('weekday', 'kind', 'shift_type_id'))
       or jsonb_typeof(w -> 'weekday') is distinct from 'number'
       or coalesce(w ->> 'kind', '') not in ('work', 'off') then
      return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('wishes_not_valid'));
    end if;
    if (w ->> 'weekday') !~ '^[1-7]$' then
      return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('wishes_not_valid'));
    end if;
    if (w ->> 'kind') = 'off' and coalesce(jsonb_typeof(w -> 'shift_type_id'), 'null') <> 'null' then
      return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('wishes_not_valid'));
    end if;
    if (w ->> 'kind') = 'work' and (jsonb_typeof(w -> 'shift_type_id') is distinct from 'string'
       or (w ->> 'shift_type_id') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$') then
      return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('wishes_not_valid'));
    end if;
  end loop;
  select * into p from public.institution_staff where id = p_staff_id for update;
  if p.id is null then
    return jsonb_build_object('result', 'rejected');
  end if;
  -- A shift type of this home only (the composite foreign key refuses another home's type as well).
  if exists (select 1 from jsonb_array_elements(p_wishes) e
             where e ->> 'kind' = 'work'
               and not exists (select 1 from public.institution_shift_types t
                               where t.id = (e ->> 'shift_type_id')::uuid and t.institution_id = p.institution_id)) then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('shift_type_not_found'));
  end if;
  if (select count(*) <> count(distinct ((e ->> 'weekday'), (e ->> 'kind'), lower(coalesce(e ->> 'shift_type_id', ''))))
      from jsonb_array_elements(p_wishes) e) then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('wish_duplicate'));
  end if;
  -- A weekday wished both with work and without work is refused, so the solver never has to choose between the two.
  if exists (select 1 from jsonb_array_elements(p_wishes) e group by e ->> 'weekday'
             having count(*) filter (where e ->> 'kind' = 'work') > 0 and count(*) filter (where e ->> 'kind' = 'off') > 0) then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('wish_conflict'));
  end if;
  select coalesce(jsonb_agg(jsonb_build_object('weekday', x.weekday, 'kind', x.kind, 'shift_type_id', x.shift_type_id)
                            order by x.weekday, x.kind, x.shift_type_id), '[]'::jsonb)
    into old_set from public.institution_staff_wishes x where x.staff_id = p.id;
  delete from public.institution_staff_wishes where staff_id = p.id;
  insert into public.institution_staff_wishes (institution_id, staff_id, weekday, kind, shift_type_id, created_by)
    select p.institution_id, p.id, (e ->> 'weekday')::smallint, e ->> 'kind', (e ->> 'shift_type_id')::uuid, (select auth.uid())
    from jsonb_array_elements(p_wishes) e;
  select coalesce(jsonb_agg(jsonb_build_object('weekday', x.weekday, 'kind', x.kind, 'shift_type_id', x.shift_type_id)
                            order by x.weekday, x.kind, x.shift_type_id), '[]'::jsonb)
    into new_set from public.institution_staff_wishes x where x.staff_id = p.id;
  perform private.institution_audit(p.institution_id, 'institution_set_staff_wishes', 'institution_staff', p.id,
    jsonb_build_object('wishes', jsonb_build_object('old', old_set, 'new', new_set)));
  return jsonb_build_object('result', 'ok', 'wishes', jsonb_array_length(new_set));
end $function$;

revoke all on function public.institution_set_staff_wishes(p_staff_id uuid, p_wishes jsonb) from public, anon, authenticated, service_role;
