-- HD-3a «Optimierung (feste Regeln)», slice 2d: wishes per person (FE-125, brief docs/agents/briefs/HD.md §5b PO
-- amendment 2026-11-24 19:39; rule catalogue docs/engineering/HD_RULE_CATALOGUE.md W-1, W-2 and §4). Synthetic
-- simulation only; fixed, checkable rules, no AI.
--   * `institution_staff_wishes`: per person an ISO weekday (1 = Monday) with a shift type of the home (`work`, W-1
--     «arbeitet gern Mo Frühdienst») or a weekday without work (`off`, W-2 «Di frei»). No free text, no reason column
--     (no health data). RLS on and no grant to anon/authenticated, like every institution table: read only through
--     `institution_plan` (every member, like the other person data), written only through the command below.
--   * `institution_set_staff_wishes(staff, wishes)` (lead or planner of the same home): replaces the person's whole set
--     under the staff row lock (two concurrent calls are serialised; membership is checked before the lock), refuses
--     a malformed entry, a shift type of another home, a duplicate and a weekday wished both with and without work;
--     LEAVE1-3 and one audit event with the old and the new set.
--   * `institution_plan` returns `wishes` (whole-file re-creation from its canonical file, only this key added).
-- A wish never makes a person permitted and never breaks a mandatory rule: the draft uses it as an order only.
-- Every function is created whole from its canonical file (STAB-1, TESTS 6). Idempotent (if not exists / create or
-- replace). Way back: re-create institution_plan from its previous file, drop the command and the table.

create table if not exists public.institution_staff_wishes (
  id             uuid primary key default gen_random_uuid(),
  institution_id uuid not null references public.institutions (id) on delete cascade,
  staff_id       uuid not null,
  weekday        smallint not null check (weekday between 1 and 7),
  kind           text not null check (kind in ('work', 'off')),
  shift_type_id  uuid,
  created_by     uuid,
  created_at     timestamptz not null default private.now(),
  check ((kind = 'work') = (shift_type_id is not null)),
  unique nulls not distinct (staff_id, weekday, kind, shift_type_id),
  foreign key (staff_id, institution_id) references public.institution_staff (id, institution_id) on delete cascade,
  foreign key (shift_type_id, institution_id) references public.institution_shift_types (id, institution_id) on delete cascade
);
comment on table public.institution_staff_wishes is
  'HD-3a (FE-125): wishes of a person as set by the home: weekday with a shift type (work) or without work (off). '
  'An order for the draft only, never a mandatory rule. Deliberately no free text and no reason column.';
create index if not exists institution_staff_wishes_by_inst on public.institution_staff_wishes (institution_id, staff_id);
alter table public.institution_staff_wishes enable row level security;
revoke all on public.institution_staff_wishes from public, anon, authenticated;

