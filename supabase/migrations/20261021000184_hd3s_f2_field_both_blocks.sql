-- public.field_visits(p_date date)
CREATE OR REPLACE FUNCTION public.field_visits(p_date date)
 RETURNS TABLE(visit_id uuid, visit_date date, time_start time without time zone, time_end time without time zone, status text, services_provided text[], team_id uuid, team_name text, case_id uuid, client_name text, care_needs text[], address text, plz text, ort text, events jsonb, planned_minutes_a integer, planned_minutes_b integer, planned_minutes_c integer, is_needs_assessment boolean, responsible_me boolean, responsible_set boolean, care_goals text[], suspended boolean, pause_reason text, system_end_reason text, from_take boolean, carried_from_previous_day boolean, take_block smallint, take_blocks text)
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
  select v.id, v.visit_date, v.time_start, v.time_end, v.status, v.services_provided,
         t.id, t.name,
         c.id, nullif(btrim(concat_ws(' ', c.first_name, c.last_name)), ''),
         c.care_needs, c.address, coalesce(c.plz, tp.postcode), coalesce(c.ort, tp.city),  -- BK-E1B
         coalesce((
           select jsonb_agg(jsonb_build_object(
                    'id', e.id,
                    'type', e.event_type,
                    'at', coalesce(lc.corrected_at, e.occurred_at),
                    'recorded_at', e.occurred_at,
                    'corrected', lc.corrected_at is not null,
                    'reason', lc.reason)
                  order by e.id)
           from public.visit_events e
           left join lateral (
             select x.corrected_at, x.reason from public.visit_time_corrections x
             where x.event_id = e.id order by x.created_at desc, x.id desc limit 1
           ) lc on true
           where e.visit_id = v.id
         ), '[]'::jsonb),
         v.planned_minutes_a, v.planned_minutes_b, v.planned_minutes_c, v.is_needs_assessment,
         v.responsible_user_id = (select auth.uid()), v.responsible_user_id is not null,
         coalesce((select array_agg(i.goal order by i.category, i.service) from public.care_plan_items i
                   where i.case_id = v.case_id and i.active and i.goal is not null), '{}'),
         v.suspended_at is not null,
         case when v.suspended_at is not null then
           (select e.reason_code from public.case_lifecycle_events e where e.case_id = v.case_id and e.kind = 'pause'
            order by e.created_at desc limit 1) end,
         v.system_end_reason,  -- BK-E1B-R (CGR-242 (c))
         v.order_take_id is not null,  -- BK-E1B-F (UXR-237, UXR-239)
         v.visit_date < p_date,  -- BK-E1C (CGR-257, UXR-248): carried from the previous day
         v.take_block,  -- HD-3s-F2 (ADR-229 (3)): 1 or 2 on a two-block take, NULL otherwise
         -- HD-3s-F2 (brief scope 3): a block card names BOTH blocks, never only one. Read from the take's own visits
         -- (same member, same team, invoker RLS as for v); NULL on a one-block take and on every non-take visit.
         case when v.take_block is not null then
           (select string_agg(to_char(s.time_start, 'HH24:MI') || ' – ' || to_char(s.time_end, 'HH24:MI'), ' und '
                              order by s.take_block)
            from public.care_visits s
            where s.order_take_id = v.order_take_id and s.take_block is not null) end
  from public.care_visits v
  join public.team_memberships tm
    on tm.team_id = v.team_id and tm.user_id = (select auth.uid())
  join public.teams t on t.id = v.team_id
  left join public.cases c on c.id = v.case_id
  left join lateral private.take_visit_place(v.id) tp on v.order_take_id is not null
  where p_date is not null
    and v.visit_date between p_date - 1 and p_date
    and private.field_day_includes(v.visit_date, v.time_start, v.time_end, v.status, p_date)  -- BK-E1C
    and (v.order_take_id is null or v.responsible_user_id = (select auth.uid()))  -- BK-7: the named member only
  order by v.visit_date, v.time_start nulls last, v.id;
$function$;

