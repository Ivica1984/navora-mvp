-- The /field card of a block of a two-block take names BOTH blocks («Teil 1 von 2 · 07:00 – 11:30 und 16:00 – 20:00»),
-- never only one. public.field_visits returns two more columns:
--   * take_block smallint: 1 or 2 on a two-block take (care_visits.take_block, 0183), NULL otherwise;
--   * take_blocks text: both blocks of the same take, read from the take's own visits (same member and team as the row
--     itself, so the same invoker RLS and the column grants of 0138/0183 decide); NULL on a one-block take and on every
--     visit that is not from a take.
-- A new return column needs drop + create (Postgres cannot change RETURNS TABLE in place); the function is re-created
-- whole from its canonical file (STAB-1, TESTS 6), with its search_path, invoker rights (no security definer, as before),
-- the BK-7 named-member filter, the BK-E1C day rule, revoke and grants unchanged. No RLS, table, grant or audit change.
-- Fixed, checkable display rule; no AI. Synthetic simulation only.
-- Idempotent: drop function if exists + create or replace + revoke/grant. Way back: drop the function and re-create the
-- previous canonical file from git (without the two columns); the app ignores unknown columns, so either order is safe.

