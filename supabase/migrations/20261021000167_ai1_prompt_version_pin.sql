--      Version '1' is registered with the digest of today's unchanged prompt.
--   2. `private.report_draft_model_closed`: the current version must be registered (`prompt_unregistered`, fail closed);
--      the stop-rule window starts no earlier than that registration (a new version opens a fresh window, AUT-167).
--      Every earlier check is kept in the same order.
--   3. `public.reserve_report_draft_call(report, key, prompt_digest)`: refuses a digest that is not the current
--      version's (`prompt_version_mismatch`) before anything is counted. The two-argument form is dropped in the same
