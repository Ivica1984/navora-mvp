  -- Team level only: no person, no request detail is stored. A display aid, never a rule input.
  if private.access_ended((select auth.uid())) then return 0; end if;  -- LEAVE1-3
  if p_list is null or p_list not in ('team_visit_alerts') then
    raise exception 'aux_list_unknown' using errcode = '22023';
