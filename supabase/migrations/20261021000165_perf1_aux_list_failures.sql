  insert into private.aux_list_failures as f (team_id, day, list_key, failures, last_at)
  select distinct tm.team_id, (private.at_zurich(private.now()))::date, p_list, 1, private.now()
  from public.team_memberships tm
  where tm.user_id = (select auth.uid())
  on conflict (team_id, day, list_key) do update set failures = f.failures + 1, last_at = excluded.last_at;
  get diagnostics n = row_count;
