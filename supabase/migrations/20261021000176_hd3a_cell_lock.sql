-- order (review of slice 3 on PR #1729, 2026-11-25 04:25, findings 1 and 4). Synthetic simulation only; fixed,
-- checkable rules, no AI.
--   * Finding 1: institution_apply_draft read institution_gap_orders without the cell lock of
--     institution_prepare_gap_order. Under READ COMMITTED an apply could save a row into a cell while a parallel prepare
--     found the same cell still a gap and prepared an external order (both commit): an external team booked for a cell
--     that is filled internally. Now both take `private.institution_cell_lock(station, shift type, day)`, one key source:
--     the apply takes every cell of its draft after the person locks and before the first row, sorted; prepare takes
--     its one cell as before. Whichever commits first is seen by the other (concurrency case G, both orders).
--   * Finding 4: the apply checks the caller's role again after the person locks and before anything is recorded, so a
--     role removed while it waited leaves no run record and no audit event.
