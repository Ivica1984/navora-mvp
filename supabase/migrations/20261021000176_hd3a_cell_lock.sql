CREATE OR REPLACE FUNCTION private.institution_cell_lock(p_station_id uuid, p_shift_type_id uuid, p_work_date date)
 RETURNS void
 LANGUAGE sql
 SET search_path TO ''
AS $function$
  -- HD-3a (review 2026-11-25 04:25, finding 1): one transaction at a time per plan cell (station, shift type, day) for
  -- every command that decides on the cell's gap state: institution_prepare_gap_order (an external order for a gap) and
  -- institution_apply_draft (internal rows for the same cell). One key source, so the two can never drift apart. Held
  -- until the transaction ends. The date is formatted explicitly, so the key does not depend on the session DateStyle.
  select pg_advisory_xact_lock(hashtextextended('institution_gap:' || p_station_id::text || ':' || p_shift_type_id::text
                                                || ':' || to_char(p_work_date, 'YYYY-MM-DD'), 0))
$function$;

