  -- As for sending: only a person who may order for the home's client account takes an order back.
  if not private.is_client_member(g.client_account_id) then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('not_client_member'));
  end if;
  -- Lock order as in take_order and acknowledge_take: the order row first, then the person (in the take-visit trigger).
  select * into o from public.partner_requests where id = g.order_id and order_kind is not null for update;
  if o.id is null then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('not_found'));
  end if;
  -- CGR-234 (c) / CGR-242 (e): nothing is released after the start; a started shift is never withdrawn silently.
  if o.starts_at <= private.now() then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('order_started'));
  end if;
  -- HD.md §3: withdrawal is offered for A (offer out), K (not covered) and N (no longer covered) only. A confirmed
  -- person (G) and a take awaiting her confirmation (T) are not withdrawn here (no client cancellation of a person).
  select c.cover_state into cov from private.order_cover(o.id, private.now()) c;
  if cov = 'covered' then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('covered'));
  end if;
  if cov = 'pending_acknowledgement' then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('awaiting_acknowledgement'));
  end if;
  select * into k from public.order_takes t where t.order_id = o.id and t.released_at is null for update;
  if k.id is not null and private.take_visit_under_way(k.id) then  -- BK-E1B-R (CGR-244): never a silent release
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('visit_under_way'));
  end if;
  -- 1. The order is withdrawn: no team is offered it, no new round is screened, no take is accepted (order_cover,
  --    team_order_offers, screen_order_reach, take_order read withdrawn_at).
  update public.partner_requests set withdrawn_at = private.now(), withdrawn_by = uid where id = o.id;
  -- 2. A live take is released with its own reason; the take-visit trigger cancels the team's planned visit
  --    (end_take_visit: system_end_reason `order_withdrawn`). Released, never deleted.
  if k.id is not null then
    update public.order_takes set released_at = private.now(), release_reason = 'withdrawn'
      where id = k.id and released_at is null;
    released := found;
  end if;
  update public.institution_gap_orders set state = 'withdrawn', withdrawn_by = uid, withdrawn_at = private.now()
    where id = g.id;
  perform private.institution_audit(g.institution_id, 'institution_withdraw_gap_order', 'institution_gap_orders', g.id,
    jsonb_build_object('order_id', o.id, 'cover_state', cov, 'take_released', released));
  return jsonb_build_object('result', 'ok', 'order_id', o.id, 'take_released', released);
end $function$;

