CREATE OR REPLACE FUNCTION private.order_offer_reasons(p_order_id uuid, p_team_id uuid)
 RETURNS text[]
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  -- ORDER-F1-F5: the clock is read exactly once per call, whatever join order the planner picks for knows_client.
  -- `clock` is materialised and read in the FROM of the outer select (one row), so private.now() runs once; the
  -- knows_client subquery compares against that value instead of calling private.now() per row of the client's
  -- orders (pgTAP 181). Clause codes and their conditions are those of BK-c3 (0137), unchanged.
  with clock as materialized (select private.now() as now_)
  select array_remove(array[
    case when exists (select 1 from public.team_memberships m
                      where m.team_id = p_team_id
                        and private.order_member_step(p_order_id, p_team_id, m.user_id) = 4)
         then 'member_free' end,
    case when exists (select 1 from public.order_takes t
                      join public.partner_requests q on q.id = t.order_id
                      join public.partner_requests o on o.id = p_order_id
                      where t.team_id = p_team_id
                        and q.id <> o.id
                        and q.client_account_id = o.client_account_id
                        and q.ends_at <= c.now_
                        and t.acknowledged_at is not null
                        and t.released_at is null)
         then 'knows_client' end
  ], null)
  from clock c
$function$;

