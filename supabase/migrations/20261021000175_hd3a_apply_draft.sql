-- rev. 2 «Apply and races»; rule catalogue docs/engineering/HD_RULE_CATALOGUE.md §1 step 8). Synthetic simulation
-- only; fixed, checkable rules, no AI.
--   * `institution_draft_runs`: one row per take-over of a draft (run record for M1, AUT-201): the apply id the client
--     sent, who, when, rows offered and saved, the refused rows with their reason and the saved assignment ids.
--     Provenance `optimizer_rules` only («Optimierung (feste Regeln)», ADR-224 point 7). No free text, no person
--     names. RLS on and no grant to anon/authenticated, like every institution table; written only by the command.
--   * `institution_apply_draft(home, apply_id, rows)` (lead or planner of the home): locks every person of the draft
--     in id order (the first lock of institution_assign_staff), then sends each row through institution_assign_staff
--     itself without a confirmation, so absence, double booking, overlap and every planning rule are decided by one
--     source; a planning rule refuses the row (never an override). A row into a cell with an active external order or
--     a cell already staffed is refused too. Partial take-over: refused rows are reported and stay gaps. A repeat with
--     the same apply id answers `already_applied` and writes nothing. LEAVE1-3; one audit event for the batch plus the
--     event of every saved row.
-- The function is created whole from its canonical file (STAB-1, TESTS 6); no existing function changes. Idempotent
-- (if not exists / create or replace). Way back: drop the command and the table (saved assignments stay, they are
-- ordinary assignments with their own audit events).

create table if not exists public.institution_draft_runs (
  id             uuid primary key,
  institution_id uuid not null references public.institutions (id) on delete cascade,
  applied_by     uuid,
  applied_at     timestamptz not null default private.now(),
  provenance     text not null default 'optimizer_rules'
                   constraint institution_draft_runs_provenance_check check (provenance in ('optimizer_rules')),
  rows_offered   integer not null constraint institution_draft_runs_offered_check check (rows_offered between 1 and 2000),
  rows_applied   integer not null default 0,
  refused        jsonb not null default '[]'::jsonb,
  assignment_ids uuid[] not null default '{}',
  constraint institution_draft_runs_counts_check check (rows_applied between 0 and rows_offered)
);
