-- public.institution_set_planning_limits(p_institution_id uuid, p_min_rest_hours integer, p_max_consecutive_days integer)
CREATE OR REPLACE FUNCTION public.institution_set_planning_limits(p_institution_id uuid, p_min_rest_hours integer, p_max_consecutive_days integer)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  h public.institutions;
begin
  perform private.assert_access_open();  -- LEAVE1-3
  -- Only the lead sets the home's planning limits (a planner plans within them).
  if p_institution_id is null or not private.is_institution_member(p_institution_id, array['lead']) then
    return jsonb_build_object('result', 'rejected');
  end if;
  -- Founder parameters for the simulation (FE-119), «Arbeitszeitgesetz nicht abschliessend geprüft»; the ranges are
  -- input checks only, not a legal rule.
  if p_min_rest_hours is null or p_min_rest_hours < 1 or p_min_rest_hours > 24
     or p_max_consecutive_days is null or p_max_consecutive_days < 1 or p_max_consecutive_days > 14 then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('limits_not_valid'));
  end if;
  select * into h from public.institutions where id = p_institution_id for update;
  if h.id is null then
    return jsonb_build_object('result', 'rejected');
  end if;
  update public.institutions set min_rest_hours = p_min_rest_hours, max_consecutive_days = p_max_consecutive_days
    where id = h.id;
  perform private.institution_audit(h.id, 'institution_set_planning_limits', 'institutions', h.id,
    jsonb_build_object('min_rest_hours', jsonb_build_object('old', h.min_rest_hours, 'new', p_min_rest_hours),
                       'max_consecutive_days', jsonb_build_object('old', h.max_consecutive_days, 'new', p_max_consecutive_days)));
  return jsonb_build_object('result', 'ok');
end $function$;

