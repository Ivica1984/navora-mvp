-- public.institution_record_absence(p_institution_id uuid, p_staff_id uuid, p_starts_on date, p_ends_on date, p_kind text)
CREATE OR REPLACE FUNCTION public.institution_record_absence(p_institution_id uuid, p_staff_id uuid, p_starts_on date, p_ends_on date, p_kind text DEFAULT 'absent'::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  p public.institution_staff;
  new_id uuid;
begin
  perform private.assert_access_open();  -- LEAVE1-3
  if p_institution_id is null or not private.is_institution_member(p_institution_id, array['lead', 'planner']) then
    return jsonb_build_object('result', 'rejected');
  end if;
  -- HD-3a (FE-119, FE-120): only the four neutral types; never a sickness type, never a reason (no health data).
  if p_kind is null or p_kind not in ('vacation', 'training', 'compensation', 'absent') then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('kind_not_valid'));
  end if;
  select * into p from public.institution_staff where id = p_staff_id and institution_id = p_institution_id for update;
  if p.id is null then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('not_found'));
  end if;
  if p_starts_on is null or p_ends_on is null or p_ends_on < p_starts_on or p_ends_on - p_starts_on > 366 then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('dates_not_valid'));
  end if;
  if exists (select 1 from public.institution_absences a where a.staff_id = p.id
             and a.starts_on <= p_ends_on and a.ends_on >= p_starts_on) then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('absence_overlaps'));
  end if;
  insert into public.institution_absences (institution_id, staff_id, starts_on, ends_on, kind, created_by)
    values (p_institution_id, p.id, p_starts_on, p_ends_on, p_kind, (select auth.uid()))
    returning id into new_id;
  -- The assignments stay: the plan then shows the person as absent and the cell as a gap (the home decides).
  perform private.institution_audit(p_institution_id, 'institution_record_absence', 'institution_absences', new_id,
    jsonb_build_object('staff_id', p.id, 'starts_on', p_starts_on, 'ends_on', p_ends_on, 'kind', p_kind));
  return jsonb_build_object('result', 'ok', 'absence_id', new_id,
    -- HD-1 R3: every shift touching an absence day counts, also the night D-1 -> D.
    'affected_assignments', (select count(*) from public.institution_assignments a
                             join public.institution_shift_types t on t.id = a.shift_type_id
                             where a.staff_id = p.id and a.work_date between p_starts_on - 1 and p_ends_on
                               and private.institution_shift_days(a.work_date, t.starts_at, t.ends_at)
                                   && daterange(p_starts_on, p_ends_on, '[]')));
end $function$;

