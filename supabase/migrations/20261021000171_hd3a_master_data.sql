-- public.institution_set_staff_planning(p_staff_id uuid, p_pensum_pct integer, p_shift_model text)
CREATE OR REPLACE FUNCTION public.institution_set_staff_planning(p_staff_id uuid, p_pensum_pct integer, p_shift_model text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  p public.institution_staff;
begin
  perform private.assert_access_open();  -- LEAVE1-3
  -- Membership first, then the row lock (a non-member never holds a lock on the home's staff row).
  if p_staff_id is null or not private.is_institution_member(
       (select s.institution_id from public.institution_staff s where s.id = p_staff_id), array['lead', 'planner']) then
    return jsonb_build_object('result', 'rejected');
  end if;
  -- HD-3a master data (#1712): Pensum 10-100 % or not entered (NULL: the person is not planned automatically).
  if p_pensum_pct is not null and (p_pensum_pct < 10 or p_pensum_pct > 100) then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('pensum_not_valid'));
  end if;
  if p_shift_model is null or p_shift_model not in ('any', 'day_only', 'late_only', 'night_only', 'no_night') then
    return jsonb_build_object('result', 'invalid', 'problems', jsonb_build_array('shift_model_not_valid'));
  end if;
  select * into p from public.institution_staff where id = p_staff_id for update;
  if p.id is null then
    return jsonb_build_object('result', 'rejected');
  end if;
  update public.institution_staff set pensum_pct = p_pensum_pct, shift_model = p_shift_model where id = p.id;
  perform private.institution_audit(p.institution_id, 'institution_set_staff_planning', 'institution_staff', p.id,
    jsonb_build_object('pensum_pct', jsonb_build_object('old', p.pensum_pct, 'new', p_pensum_pct),
                       'shift_model', jsonb_build_object('old', p.shift_model, 'new', p_shift_model)));
  return jsonb_build_object('result', 'ok');
end $function$;

