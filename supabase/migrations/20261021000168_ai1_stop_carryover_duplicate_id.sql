-- private.report_draft_model_closed(p_report visit_reports, p_uid uuid)
CREATE OR REPLACE FUNCTION private.report_draft_model_closed(p_report visit_reports, p_uid uuid)
 RETURNS text
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  rule  public.report_draft_stop_rules%rowtype;
  st    record;
  since timestamptz;
  ver   record;
begin
  if p_uid is null or p_report.id is null or not private.is_org_member(p_report.organization_id)
     or not private.is_team_member(p_report.team_id) or private.access_ended(p_uid) then
    return 'not_team_member';
  end if;
  if p_report.status <> 'draft' then return 'not_draft'; end if;
  if p_report.performer_id <> p_uid then return 'not_performer'; end if;
  if not coalesce((select o.simulation from public.organizations o where o.id = p_report.organization_id), false) then
    return 'not_simulation_org';
  end if;
  -- AI1 / ADR-227 point 3: the database kill switch, read on every request (no restart). The newest event for all
  -- organisations wins over an organisation's own event; an organisation event only applies while «all» is not off.
  if private.ai_function_off('report_draft_model', p_report.organization_id) then return 'switched_off'; end if;
  if not exists (select 1 from public.ai_agent_fields f where f.agent_key = 'report_draft_model' and f.field = 'summary_line') then
    return 'ledger_missing';
  end if;
  -- AI1 contract item 2 (AUT-167): the current agent version must have a registered prompt digest; its registration
  -- time starts the stop-rule window, so a new prompt version is never judged by the corrections of the previous one.
  select pv.registered_at into since
  from public.ai_agent_definitions d
  join private.ai_agent_prompt_versions pv on pv.agent_key = d.key and pv.version = d.version
  where d.key = 'report_draft_model';
  if since is null then return 'prompt_unregistered'; end if;
  select * into rule from public.report_draft_stop_rules r where r.agent_key = 'report_draft_model';
  if not found then return 'no_threshold'; end if;
  select * into st from private.aig1_window_stats(p_report.organization_id, 'report_draft_model',
                                                  greatest(private.now() - make_interval(days => rule.stop_window_days), since),
                                                  private.now() + interval '1 second');
  if st.decided >= rule.stop_min_decided and st.share > rule.stop_share then return 'stop_rule'; end if;
  -- AUT-194: a stop an earlier prompt version reached carries over to every later version. Each earlier version is
  -- judged on its last window, which ends at the next version's registration; only a «cleared» switch event (eng and
  -- cra) for all organisations or this organisation at or after that end lifts it. A version bump never lifts a stop.
  for ver in
    select x.from_at, x.to_at
    from (select p.registered_at as from_at,
                 lead(p.registered_at) over (order by p.registered_at, p.version) as to_at
          from private.ai_agent_prompt_versions p
          where p.agent_key = 'report_draft_model') x
    where x.from_at < since and x.to_at is not null and x.to_at <= since
  loop
    select * into st from private.aig1_window_stats(p_report.organization_id, 'report_draft_model',
                                                    greatest(ver.to_at - make_interval(days => rule.stop_window_days), ver.from_at),
                                                    ver.to_at);
    if st.decided >= rule.stop_min_decided and st.share > rule.stop_share
       and not exists (select 1 from private.ai_function_switch_events e
                       where e.function_key = 'report_draft_model' and not e.off and e.created_at >= ver.to_at
                         and (e.organization_id is null or e.organization_id = p_report.organization_id)) then
      return 'stop_rule';
    end if;
  end loop;
  return null;
end;
$function$;

